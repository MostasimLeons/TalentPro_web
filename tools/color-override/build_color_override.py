"""
Generate assets/tp3d/css/tp-3d-colors.css from the theme's compiled Tailwind CSS.

The theme hard-codes the old coral/teal in ~95 compiled rules (not only in the
--color-* variables), so overriding variables alone would leave mixed colours.
This script copies ONLY the declarations that contain the old colours, keeps
their original selector / @media / @layer wrappers, and swaps the colour.
The output keeps the original rule order and loads after tailwind.css, so each
rule wins at the same specificity while hover/focus variants keep their order.

Usage:  python -I build_color_override.py <tailwind.css> <out.css>
Re-run it whenever the theme's tailwind.css is rebuilt.
"""
import os
import re
import sys

# old -> new   (alpha suffixes such as #dd523d59 are preserved)
COLOR_MAP = {
    # Buttons/links use a deeper blue so white text passes WCAG AA (4.87:1).
    # The bright logo blue #00adee stays for glows/nodes via --tp-accent.
    "dd523d": "0077b6",  # CTA / accent  -> deeper logo blue
    "c8452f": "00669c",  # CTA hover     -> one step darker (6.21:1 with white)
    "062826": "101818",  # dark teal bg  -> requested dark
    "041d1b": "0b1111",  # footer bottom -> darker step of #101818
    "041c1a": "0b1111",  # marquee fade  -> matches footer bottom
    "0f5d59": "1e2b2b",  # card gradient top (lighter teal) -> lighter step of #101818
}
COLOR_RE = re.compile(r"#(" + "|".join(COLOR_MAP) + r")([0-9a-f]{2})?(?![0-9a-f])", re.I)

WHOLE_BLOCK_AT = ("@keyframes", "@-webkit-keyframes", "@property", "@font-face")


def recolor(text):
    return COLOR_RE.sub(lambda m: "#" + COLOR_MAP[m.group(1).lower()] + (m.group(2) or ""), text)


def parse(css, i=0):
    """Return (items, index). items: ('decl', text) | ('block', prelude, items, raw)."""
    items, buf, start = [], [], i
    quote = None
    paren = 0
    while i < len(css):
        ch = css[i]
        if quote:
            buf.append(ch)
            if ch == "\\":
                buf.append(css[i + 1]); i += 2; continue
            if ch == quote:
                quote = None
            i += 1; continue
        if css.startswith("/*", i):
            end = css.find("*/", i + 2)
            i = len(css) if end < 0 else end + 2
            continue
        if ch in "\"'":
            quote = ch; buf.append(ch)
        elif ch == "(":
            paren += 1; buf.append(ch)
        elif ch == ")":
            paren -= 1; buf.append(ch)
        elif ch == ";" and paren == 0:
            t = "".join(buf).strip()
            if t:
                items.append(("decl", t))
            buf = []
        elif ch == "{":
            prelude = "".join(buf).strip()
            body_start = i + 1
            children, i = parse(css, i + 1)
            items.append(("block", prelude, children, css[body_start:i - 1]))
            buf = []
            continue
        elif ch == "}":
            t = "".join(buf).strip()
            if t:
                items.append(("decl", t))
            return items, i + 1
        else:
            buf.append(ch)
        i += 1
    t = "".join(buf).strip()
    if t:
        items.append(("decl", t))
    return items, i


def emit(items):
    out = []
    for it in items:
        if it[0] == "decl":
            if COLOR_RE.search(it[1]) and not it[1].startswith("@"):
                out.append(recolor(it[1]) + ";")
            continue
        _, prelude, children, raw = it
        if prelude.startswith(WHOLE_BLOCK_AT):
            if COLOR_RE.search(raw):
                out.append(prelude + "{" + recolor(raw) + "}")
            continue
        inner = emit(children)
        if inner:
            out.append(prelude + "{" + inner + "}")
    return "".join(out)


def main(src, dst):
    css = open(src, encoding="utf-8").read()
    items, _ = parse(css)
    layer_stmt = re.match(r"(?:/\*.*?\*/)?\s*(@layer [^{;]+;)", css, re.S)
    body = emit(items)
    header = (
        "/* TalentPro 3D redesign – colour override (generated by build_color_override.py).\n"
        " * Old -> new: " + ", ".join("#%s->#%s" % kv for kv in COLOR_MAP.items()) + "\n"
        " * Remove this file (or its enqueue) to restore the original colours. */\n"
    )
    extra = (
        "\n/* Tokens for the 3D layer */\n"
        "/* --tp-accent = bright logo blue for decoration (glows, nodes); --tp-accent-ui = buttons/links */\n"
        ":root{--tp-accent:#00adee;--tp-accent-ui:#0077b6;--tp-accent-ui-hover:#00669c;--tp-dark:#101818}\n"
        "/* Inline-style gradient on the 'Solve. Build. Operate.' cards (style attribute in the template) */\n"
        "[style*=\"#062826\"][style*=\"#0f5d59\"]{background-image:linear-gradient(0deg,#101818 0%,#1e2b2b 100%)!important}\n"
    )
    # Hand-written additions kept next to this script (header nav states etc.)
    manual = os.path.join(os.path.dirname(os.path.abspath(__file__)), "nav-states.css")
    if os.path.exists(manual):
        extra += open(manual, encoding="utf-8").read()
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + (layer_stmt.group(1) + "\n" if layer_stmt else "") + body + extra)
    print("rules written:", body.count("{") - body.count("@"), "bytes:", len(header) + len(body) + len(extra))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
